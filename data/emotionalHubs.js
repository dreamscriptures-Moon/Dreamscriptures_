function makeLightHub(slug, title) {
  return {
    ...baseHubDefaults,
    title,
    domain: "emotional pattern",
    intro: `${title} can shape dream imagery when this feeling is asking for more attention, honesty, or care in waking life.`,
    relatedHubs: [],
    emotionalPathways: [],
    emotionalJourney: {
      before: [],
      deeper: [],
      healing: ["emotional-healing", "personal-growth"].filter((item) => item !== slug),
    },
    guide: `/emotions/${slug}`,
  };
}

